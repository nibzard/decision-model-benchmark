"""Build and hash all five suite item files in one command.

    uv run dmb build            (or: python -m dmb.suites.build)

Downloads real data into ``data/raw/`` (with license files), generates
the synthetic suites, writes ``data/suites/<suite>.jsonl``, and records
every file's SHA-256 in ``data/suites/hashes.json``. Items are frozen at
release: a release is not a release until these hashes are in the run
manifest.
"""

from __future__ import annotations

import json
from pathlib import Path

from . import s1_intent77, s2_spam, s3_cardinality, s4_order, s5_confidence
from .items import DecisionItem, save_items
from .sources import SOURCES

# suite file name -> builder that returns (items, notes)
SUITE_ORDER = ["s1_intent77", "s2_spam", "s3_cardinality", "s4_order", "s5_confidence"]

SUITE_IDS = {
    "s1_intent77": s1_intent77.SUITE_ID,
    "s2_spam": s2_spam.SUITE_ID,
    "s3_cardinality": s3_cardinality.SUITE_ID,
    "s4_order": s4_order.SUITE_ID,
    "s5_confidence": s5_confidence.SUITE_ID,
}

LICENSES_MD = """# Suite data licenses and attribution

- **S1 intent-77 and S4 order-stability**: Banking77, Casanueva et al.,
  PolyAI-LDN task-specific datasets, CC BY 4.0. S4 permutes the options
  around S1 spare utterances and remains a derivative of Banking77.
  License: https://creativecommons.org/licenses/by/4.0/
  Repository: https://github.com/PolyAI-LDN/task-specific-datasets
  Exact repository commit, CSV and license hashes are in hashes.json.
  License text is saved to data/raw/banking77-LICENSE.
- **S2 gate-spam**: SMS Spam Collection, Almeida, Hidalgo and Yamakami (2011),
  "Contributions to the Study of SMS Spam Filtering", CEAS 2011.
  Current UCI page lists CC BY 4.0:
  https://archive.ics.uci.edu/dataset/228/sms+spam+collection
  DMB keeps message text local as its publication privacy policy;
  published archives retain approved numeric observations only.
- **S3 cardinality and S5 confidence**: generated by DMB with seed 20260918;
  no third-party item text. Regenerate with uv run dmb build.
"""


def build_all(root: Path | None = None) -> dict[str, dict]:
    """Build every suite; returns the hashes.json payload."""
    base = root if root is not None else Path(__file__).resolve().parents[3]
    raw_dir = base / "data" / "raw"
    suites_dir = base / "data" / "suites"
    suites_dir.mkdir(parents=True, exist_ok=True)

    s2_path = s2_spam.download(raw_dir)
    s2_rows = s2_spam.load_rows(s2_path)
    s2_items = s2_spam.build_items(s2_rows)

    s1_csv, s1_labels = s1_intent77.download(raw_dir)
    s1_rows = s1_intent77.load_rows(s1_csv)
    s1_items = s1_intent77.build_items(s1_rows, s1_labels)

    s3_items = s3_cardinality.build_items()
    s4_items = s4_order.build_items(s1_items)
    s5_items = s5_confidence.build_items()

    built: dict[str, list[DecisionItem]] = {
        "s1_intent77": s1_items,
        "s2_spam": s2_items,
        "s3_cardinality": s3_items,
        "s4_order": s4_items,
        "s5_confidence": s5_items,
    }

    hashes: dict[str, dict] = {}
    for file_key in SUITE_ORDER:
        items = built[file_key]
        path = suites_dir / f"{file_key}.jsonl"
        digest = save_items(items, path)
        hashes[file_key] = {
            "suite": SUITE_IDS[file_key],
            "path": str(path.relative_to(base)),
            "items": len(items),
            "sha256": digest,
        }
        print(f"built {file_key:15s} {len(items):4d} items  sha256={digest[:16]}...")

    hashes["_meta"] = {"seed": 20260918, "generator": "dmb.suites.build", "sources": SOURCES}
    (suites_dir / "hashes.json").write_text(
        json.dumps(hashes, indent=2) + "\n", encoding="utf-8"
    )
    (base / "data" / "LICENSES.md").write_text(LICENSES_MD, encoding="utf-8")
    print("wrote data/suites/hashes.json and data/LICENSES.md")
    return hashes


if __name__ == "__main__":
    build_all()
